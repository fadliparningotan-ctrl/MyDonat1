-- Skema database My Donat (MySQL / MariaDB / TiDB)
CREATE TABLE IF NOT EXISTS admin (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nama VARCHAR(100) DEFAULT NULL,
  username VARCHAR(50) NOT NULL UNIQUE,
  password VARCHAR(64) NOT NULL,
  email VARCHAR(100) DEFAULT NULL,
  npm VARCHAR(30) DEFAULT NULL,
  foto VARCHAR(255) DEFAULT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS users (
  id INT AUTO_INCREMENT PRIMARY KEY,
  nama VARCHAR(100) DEFAULT NULL,
  username VARCHAR(50) NOT NULL UNIQUE,
  password VARCHAR(64) DEFAULT NULL,
  email VARCHAR(100) DEFAULT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS kategori (
  id_kategori INT AUTO_INCREMENT PRIMARY KEY,
  nama_kategori VARCHAR(100) NOT NULL,
  deskripsi TEXT
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS produk (
  id_produk INT AUTO_INCREMENT PRIMARY KEY,
  nama_produk VARCHAR(150) NOT NULL,
  kategori VARCHAR(100) DEFAULT NULL,
  harga_produk DECIMAL(12,2) NOT NULL DEFAULT 0,
  stok INT NOT NULL DEFAULT 0,
  gambar VARCHAR(255) DEFAULT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS transaksi (
  id_transaksi INT AUTO_INCREMENT PRIMARY KEY,
  tgl_transaksi DATETIME DEFAULT CURRENT_TIMESTAMP,
  total_bayar DECIMAL(14,2) NOT NULL DEFAULT 0,
  metode_pembayaran VARCHAR(50) DEFAULT 'Cash',
  status_pembayaran VARCHAR(30) DEFAULT 'Lunas',
  status VARCHAR(30) DEFAULT 'Lunas'
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS detail_transaksi (
  id_detail INT AUTO_INCREMENT PRIMARY KEY,
  kode_transaksi VARCHAR(30) NOT NULL,
  id_produk INT NOT NULL,
  qty INT NOT NULL DEFAULT 1,
  subtotal DECIMAL(14,2) NOT NULL DEFAULT 0,
  INDEX (kode_transaksi),
  INDEX (id_produk)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS php_sessions (
  id VARCHAR(128) NOT NULL PRIMARY KEY,
  data MEDIUMBLOB NOT NULL,
  updated_at INT NOT NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS file_upload (
  path VARCHAR(255) NOT NULL PRIMARY KEY,
  mime VARCHAR(100) NOT NULL,
  data LONGBLOB NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
